import { jsPDF } from 'jspdf';
import 'jspdf-autotable';
import { formatCurrency, formatDate } from './utils';

export function generateInvoicePDF(order: any, party: any) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  
  // Header
  doc.setFontSize(20);
  doc.setTextColor(11, 99, 206); // Shreeji Blue
  doc.text('SHREEJI HEALTHCARE', 14, 22);
  
  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text('Wholesale Pharma Distributor', 14, 28);
  doc.text('GSTIN: 24AAACS1234A1Z5', 14, 34);
  
  // Invoice Title
  doc.setFontSize(16);
  doc.setTextColor(0, 0, 0);
  doc.text('TAX INVOICE', pageWidth - 14, 22, { align: 'right' });
  
  doc.setFontSize(10);
  doc.text(`Order No: ${order.orderNumber || order.id.slice(0,8)}`, pageWidth - 14, 28, { align: 'right' });
  doc.text(`Date: ${formatDate(order.order_date || new Date())}`, pageWidth - 14, 34, { align: 'right' });
  
  // Party Details
  doc.setFontSize(11);
  doc.setTextColor(0, 0, 0);
  doc.text('Billed To:', 14, 45);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(party.partyName || party.party_name, 14, 51);
  doc.setFont('helvetica', 'normal');
  doc.text(party.address1 || '', 14, 56);
  if (party.address2) doc.text(party.address2, 14, 61);
  doc.text(`${party.city || ''}, ${party.state || ''}`, 14, party.address2 ? 66 : 61);
  if (party.gstin) doc.text(`GSTIN: ${party.gstin}`, 14, party.address2 ? 71 : 66);
  
  // Table
  const tableColumn = ["Sr.", "Product", "Batch", "Exp", "Qty", "Free", "PTR", "Amount"];
  const tableRows: any[] = [];
  
  let currentY = party.address2 ? 80 : 75;
  
  if (order.items && Array.isArray(order.items)) {
    order.items.forEach((item: any, index: number) => {
      const row = [
        index + 1,
        item.productName || item.product_name,
        item.batchNo || item.batch_no || '-',
        item.expiryDate ? formatDate(item.expiryDate) : '-',
        item.quantity,
        item.freeQuantity || 0,
        item.price || item.ptr,
        (item.quantity * (item.price || item.ptr)).toFixed(2)
      ];
      tableRows.push(row);
    });
  }

  (doc as any).autoTable({
    head: [tableColumn],
    body: tableRows,
    startY: currentY,
    theme: 'grid',
    headStyles: { fillColor: [11, 99, 206] },
    styles: { fontSize: 8 },
    columnStyles: {
      0: { cellWidth: 10 },
      4: { halign: 'right' },
      5: { halign: 'right' },
      6: { halign: 'right' },
      7: { halign: 'right' }
    }
  });

  const finalY = (doc as any).lastAutoTable.finalY + 10;
  
  // Totals
  doc.setFontSize(10);
  doc.text('Subtotal:', pageWidth - 60, finalY);
  doc.text(formatCurrency(order.subtotal || order.totalAmount), pageWidth - 14, finalY, { align: 'right' });
  
  if (order.discountAmount > 0) {
    doc.text('Discount:', pageWidth - 60, finalY + 6);
    doc.text('-' + formatCurrency(order.discountAmount), pageWidth - 14, finalY + 6, { align: 'right' });
    doc.setFont('helvetica', 'bold');
    doc.text('Total Amount:', pageWidth - 60, finalY + 14);
    doc.text(formatCurrency(order.totalAmount || order.total_amount), pageWidth - 14, finalY + 14, { align: 'right' });
  } else {
    doc.setFont('helvetica', 'bold');
    doc.text('Total Amount:', pageWidth - 60, finalY + 8);
    doc.text(formatCurrency(order.totalAmount || order.total_amount), pageWidth - 14, finalY + 8, { align: 'right' });
  }

  // Footer
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.text('Generated by Shreeji Healthcare B2B System', 14, doc.internal.pageSize.getHeight() - 10);
  
  doc.save(`Invoice_${order.orderNumber || order.id.slice(0,8)}.pdf`);
}
